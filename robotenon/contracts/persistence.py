"""Structural ports for persistence, without concrete database dependencies."""
from typing import Any, Protocol

from ..schemas import EnvironmentFeedback, SafetyStateSnapshot


class ObservationStore(Protocol):
    async def start(self) -> None: ...
    async def close(self) -> None: ...
    async def append(self, feedback: EnvironmentFeedback, payloads=None, *, durable=False) -> EnvironmentFeedback: ...
    async def read_uri_bytes(self, uri: str) -> tuple[bytes, dict[str, Any]]: ...
    async def latest(self, session_id, epoch=None): ...
    async def history(self, session_id, epoch=None, *, length=4, interval=1): ...


class SafetyStore(Protocol):
    def snapshot(self) -> SafetyStateSnapshot: ...
    def update(self, signals=(), **kwargs) -> SafetyStateSnapshot: ...
    def reconcile(self, owner, signals=(), **kwargs) -> SafetyStateSnapshot: ...
    def clear(self, **kwargs) -> SafetyStateSnapshot: ...
    def heartbeat(self, source, **kwargs) -> SafetyStateSnapshot: ...
    def clear_heartbeat(self, source) -> SafetyStateSnapshot: ...
    def recover(self, **kwargs) -> SafetyStateSnapshot: ...
    def observe_feedback(self, feedback: EnvironmentFeedback) -> SafetyStateSnapshot: ...
    def raise_level(self, level, **kwargs) -> SafetyStateSnapshot: ...
